// تنفيذ الدالة التلقائية عند اكتمال تحميل الصفحة بالكامل
window.onload = function() {
    // تعيين مصدر صورة الشعار الافتراضية
    document.getElementById('reportLogoImg').src = LOCAL_LOGO_PATH;
    // بناء استمارة مجالات التقييم الحسي
    renderDomainsForm();
    // تحديث قائمة الأسماء المحفوظة في ذاكرة LocalStorage
    updateSavedChildrenDropdown();
    // ضبط تاريخ التقييم التلقائي على تاريخ اليوم الحاضر
    document.getElementById('evalDate').valueAsDate = new Date();
};

// دالة لبناء وتجميع استمارة المجالات والبنود ديناميكياً
function renderDomainsForm() {
    // جلب حاوية الاستمارة من الـ DOM
    const container = document.getElementById('domainsContainer');
    // تفريغ محتوى الحاوية بالكامل
    container.innerHTML = '';

    // الدوران على كائنات المجالات الثمانية
    domainsData.forEach(domain => {
        // إنشاء كود HTML المبدئي للمجال الحسي
        let html = `<div class="domain-block">
            <h4 class="domain-title">${domain.name}</h4>`;

        // الدوران على البنود الـ 15 لكل مجال
        domain.items.forEach((itemText, index) => {
            // حساب رقم البند الحالي
            const num = index + 1;
            // إعداد البادئة الفريدة لمعرفات عناصر التقييم
            const fieldPrefix = `${domain.id}_${num}`;
            // إضافة HTML صف البند مع خيارات النسبة والنمط
            html += `
            <div class="item-row" data-domain="${domain.id}">
                <span>${num}. ${itemText}</span>
                <div class="controls-group">
                    <select id="${fieldPrefix}_score">
                        <option value="0">0 - طبيعي</option>
                        <option value="1">1 - بسيط</option>
                        <option value="2">2 - متوسط</option>
                        <option value="3">3 - شديد</option>
                    </select>
                    <select id="${fieldPrefix}_type">
                        <option value="hypo">نقص استجابة / خمول وبحث</option>
                        <option value="hyper">فرط استجابة / تجنب</option>
                    </select>
                </div>
            </div>`;
        });

        // إضافة صف البند اليدوي الـ 16 المخصص للأخصائي
        html += `
        <div class="manual-row" data-domain="${domain.id}">
            <label style="color:#0284c7;">➕ 16. إضافة بند سلوكي مخصص (يدوي للأخصائي):</label>
            <div style="display: flex; gap: 10px; margin-top: 5px; flex-wrap: wrap;">
                <input type="text" id="${domain.id}_manual_text" placeholder="اكتب وصف السلوك الملاحظ هنا..." style="flex: 2; min-width: 200px;">
                <select id="${domain.id}_manual_score" style="flex: 1; min-width: 120px;">
                    <option value="0">0 - طبيعي</option>
                    <option value="1">1 - بسيط</option>
                    <option value="2">2 - متوسط</option>
                    <option value="3">3 - شديد</option>
                </select>
                <select id="${domain.id}_manual_type" style="flex: 1; min-width: 140px;">
                    <option value="hypo">نقص استجابة / خمول وبحث</option>
                    <option value="hyper">فرط استجابة / تجنب</option>
                </select>
            </div>
        </div></div>`;

        // دمج عناصر المجال داخل حاوية الاستمارة
        container.innerHTML += html;
    });
}
